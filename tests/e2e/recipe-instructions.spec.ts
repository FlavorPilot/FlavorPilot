import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('writes, reorders, undoes and reopens a complete device recipe', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/en/builder');
    await page.getByRole('tab', { name: '1. Composition & balance' }).focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: '2. Preparation' })).toBeFocused();
    await expect(page.getByRole('tab', { name: '2. Preparation' })).toHaveAttribute('aria-selected', 'true');
    await page.getByLabel('About this dish').fill('A fresh salmon dish.');
    await page.getByLabel('Servings', { exact: true }).pressSequentially('12');
    await expect(page.getByLabel('Servings', { exact: true })).toHaveValue('12');
    await page.getByRole('button', { name: 'Add a step', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Step 1', exact: true })).toBeFocused();
    await page.getByRole('textbox', { name: 'Step 1', exact: true }).pressSequentially('Prepare the salmon.');
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Step 1', exact: true })).toHaveValue('');
    await page.getByRole('button', { name: 'Redo', exact: true }).click();
    await page.getByRole('button', { name: 'Add a step', exact: true }).click();
    await page.getByRole('textbox', { name: 'Step 2', exact: true }).fill('Serve with the garnish.');
    await page.getByRole('button', { name: 'Move step up: 2', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Step 1', exact: true })).toHaveValue('Serve with the garnish.');
    await page.getByRole('button', { name: 'Remove step: 1', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Step 2', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Step 2', exact: true })).toHaveValue('Prepare the salmon.');
    await page.getByRole('tab', { name: '1. Composition & balance' }).click();
    await page.getByRole('textbox', { name: 'Recipe name' }).fill('A written recipe');
    await page.getByLabel('Add an ingredient').fill('Salmon');
    await page.getByRole('option', { name: /Salmon/ }).click();
    await page.getByRole('button', { name: 'Save recipe', exact: true }).click();
    await expect(page.getByRole('dialog').getByRole('button', {name:/My account/})).toBeDisabled();
    await page.getByRole('dialog').getByRole('button', { name: 'Save recipe', exact: true }).click();
    await expect(page.getByText('Saved to this browser only.')).toBeVisible();
    await page.goto('/en/library');
    await page.getByRole('button', { name: 'Open', exact: true }).click();
    await page.getByRole('tab', { name: '2. Preparation' }).click();
    await expect(page.getByLabel('About this dish')).toHaveValue('A fresh salmon dish.');
    await expect(page.getByLabel('Servings', { exact: true })).toHaveValue('12');
    await expect(page.getByRole('textbox', { name: 'Step 1', exact: true })).toHaveValue('Serve with the garnish.');
    await page.reload();
    await page.getByRole('tab', { name: '2. Preparation' }).click();
    await expect(page.getByRole('textbox', { name: 'Step 2', exact: true })).toHaveValue('Prepare the salmon.');
    expect(errors).toEqual([]);
});

test('keeps authored text through locale changes and exports and imports version 2', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/uk/builder');
    await page.getByRole('tab', { name: '2. Приготування' }).click();
    await page.getByLabel('Про цю страву').fill('Мій авторський рецепт.');
    await page.getByRole('button', { name: 'Додати крок', exact: true }).click();
    await page.getByRole('textbox', { name: 'Крок 1', exact: true }).fill('Нарізати зелень.');
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: /Експорт/ }).click();
    const download = await downloadEvent;
    const file = await download.path();
    expect(file).toBeTruthy();
    const exported = JSON.parse(await readFile(file!, 'utf8'));
    expect(exported).toMatchObject({ format: 'flavorpilot.recipe', version: 2, description: 'Мій авторський рецепт.', items: [] });
    expect(exported.steps[0].text).toBe('Нарізати зелень.');
    await page.getByRole('link', { name: 'Змінити мову' }).click();
    await page.getByRole('tab', { name: '2. Preparation' }).click();
    await expect(page.getByLabel('About this dish')).toHaveValue('Мій авторський рецепт.');
    await expect(page.getByRole('textbox', { name: 'Step 1', exact: true })).toHaveValue('Нарізати зелень.');
    await page.getByLabel('Servings', { exact: true }).fill('2.5');
    await expect(page.getByLabel('Servings', { exact: true })).toHaveAttribute('aria-invalid', 'true');
    await expect(page.getByText('Enter a whole number from 1 to 1,000, or leave this empty.')).toBeVisible();
    await page.getByLabel('Servings', { exact: true }).fill('3');
    await expect(page.getByLabel('Servings', { exact: true })).toHaveAttribute('aria-invalid', 'false');
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await page.goto('/en/library');
    await page.locator('input[type=file]').setInputFiles(file!);
    await page.getByRole('tab', { name: '2. Preparation' }).click();
    await expect(page.getByRole('textbox', { name: 'Step 1', exact: true })).toHaveValue('Нарізати зелень.');
    await expect(page.getByLabel('Servings', { exact: true })).toHaveValue('');
});
